'use strict';

// Builds public/app.html, the page the website serves to signed-in people, from the claude.ai
// artifact (../artifact/clashbets.html). The artifact is only read, never changed. What is added:
// the shim (so window.claude exists before the page script runs), a doctype and the usual head
// tags (the artifact platform supplies those; a plain website has to), and noindex.
//
//   node site/build.js            writes site/public/app.html
//   node site/build.js --check    exits 1 if app.html is out of date (for CI)
//
// Running it again on the same page gives the same bytes, and build() leaves a page that is
// already built alone.

const fs = require('fs');
const path = require('path');

const SRC = path.join(__dirname, '..', 'artifact', 'clashbets.html');
const OUT = path.join(__dirname, 'public', 'app.html');
const SHIM = '<script src="/shim.js"></script>';
const MARK = 'Generated by site/build.js';

// Offset of the first real <script tag (not one inside an HTML comment), or -1
function firstScript(html) {
  const re = /<script\b/gi;
  let m;
  while ((m = re.exec(html))) {
    const open = html.lastIndexOf('<!--', m.index), close = html.lastIndexOf('-->', m.index);
    if (open <= close) return m.index;
  }
  return -1;
}

function build(src) {
  let out = String(src);
  // The shim goes straight before the first script, so it runs before the page's own code.
  const at = firstScript(out);
  if (at < 0) throw new Error('build: the page has no <script> tag, so there is nowhere to put the shim');
  if (out.startsWith(SHIM, at)) { /* already there */ }
  else if (out.includes(SHIM)) throw new Error('build: the shim tag is in the page but not before its first script');
  else out = out.slice(0, at) + SHIM + '\n' + out.slice(at);
  if (firstScript(out) !== out.indexOf(SHIM)) throw new Error('build: the shim is not the first script in the page');

  const head = [];
  if (!/^\s*<!doctype/i.test(out)) head.push('<!doctype html>');
  if (!out.includes(MARK)) head.push(`<!-- ${MARK} from artifact/clashbets.html. Do not edit this file: change the artifact and run "node site/build.js". -->`);
  if (!/<html[\s>]/i.test(out)) head.push('<html lang="en-GB">');
  if (!/<meta\s[^>]*charset/i.test(out)) head.push('<meta charset="utf-8">');
  if (!/<meta\s[^>]*name=["']?viewport/i.test(out)) head.push('<meta name="viewport" content="width=device-width, initial-scale=1">');
  if (!/<meta\s[^>]*name=["']?robots/i.test(out)) head.push('<meta name="robots" content="noindex">');
  if (!/<meta\s[^>]*name=["']?theme-color/i.test(out)) head.push('<meta name="theme-color" content="#0d1530">');
  if (head.length) out = head.join('\n') + '\n' + out;
  return out;
}

function main() {
  const built = build(fs.readFileSync(SRC, 'utf8'));
  if (process.argv.includes('--check')) {
    const now = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : null;
    if (now !== built) { console.error('site/public/app.html is out of date. Run: node site/build.js'); process.exit(1); }
    console.log('site/public/app.html is up to date');
    return;
  }
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  const tmp = OUT + '.tmp';
  fs.writeFileSync(tmp, built);
  fs.renameSync(tmp, OUT);
  console.log(`site/public/app.html written (${Buffer.byteLength(built)} bytes, shim before line ${built.slice(0, built.indexOf(SHIM)).split('\n').length})`);
}

if (require.main === module) main();
module.exports = { build, SHIM };
